-- Source-only distribution: schema retained; seed/imported records omitted.

CREATE TABLE social_publish_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    platform VARCHAR(32) NOT NULL,
    display_name VARCHAR(80) NOT NULL,
    credentials_encrypted TEXT NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    last_check_status VARCHAR(20) NOT NULL DEFAULT 'unchecked',
    last_check_message VARCHAR(500),
    last_checked_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_social_publish_account_platform CHECK (platform IN ('douyin', 'xiaohongshu', 'wechat_channels'))
);

CREATE INDEX idx_social_publish_accounts_user ON social_publish_accounts(user_id, platform, id);

CREATE TABLE social_publish_tasks (
    id VARCHAR(36) PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    account_id BIGINT REFERENCES social_publish_accounts(id) ON DELETE SET NULL,
    platform VARCHAR(32) NOT NULL,
    media_type VARCHAR(16) NOT NULL,
    title VARCHAR(200) NOT NULL DEFAULT '',
    description TEXT NOT NULL DEFAULT '',
    media_urls_json TEXT NOT NULL,
    cover_url TEXT,
    topics_json TEXT NOT NULL DEFAULT '[]',
    settings_json TEXT NOT NULL DEFAULT '{}',
    publish_mode VARCHAR(20) NOT NULL,
    status VARCHAR(20) NOT NULL DEFAULT 'queued',
    result_data TEXT,
    error_message TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    started_at TIMESTAMPTZ,
    finished_at TIMESTAMPTZ,
    CONSTRAINT ck_social_publish_task_platform CHECK (platform IN ('douyin', 'xiaohongshu', 'wechat_channels')),
    CONSTRAINT ck_social_publish_task_media_type CHECK (media_type IN ('video', 'images')),
    CONSTRAINT ck_social_publish_task_mode CHECK (publish_mode IN ('dry_run', 'draft', 'publish')),
    CONSTRAINT ck_social_publish_task_status CHECK (status IN ('queued', 'running', 'success', 'failed'))
);

CREATE INDEX idx_social_publish_tasks_user_created ON social_publish_tasks(user_id, created_at DESC);

CREATE INDEX idx_social_publish_tasks_account ON social_publish_tasks(account_id, created_at DESC);

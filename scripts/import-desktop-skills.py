ADAPTER = """# Inspire Studio 技能集成约定
下方技能正文是创作参考，用于指导剧本、分镜、资产或海报提示词的编写。

- 当前用户要求、已确认的剧情/角色/素材、宿主输出协议和本轮真实工具定义优先于下方示例。技能中提到的外部平台、脚本、文件路径或专用模型不代表本项目具备这些能力，不得声称已执行。
- 始终遵守主 Agent 的 CreationPlan 结构化协议：纯文本成果放入宿主允许的回复字段且 tasks 为空；只有用户要求且参数齐全时才创建图片/视频任务。不要把完整剧本直接当作一段视频的生成提示词。
- 用户指定的时长、画幅和当前模型能力优先于原文模板里的固定条件；各镜头时间轴连续，总时长与目标一致。
- 沿用已确认角色的外貌、服装、道具与参考图；分镜说明人物位置、动作起点/终点、道具状态与上下镜头的因果衔接，避免变脸、道具跳变或剧情缺环。
- 参考素材必须来自当前上传附件或真实节点，不虚构素材、URL 或 nodeId；缺少关键素材时说明需要哪一项。

"""


def sha256(content):
    return hashlib.sha256(content).hexdigest()


def main():
    if MIGRATION.exists() or DESTINATION.exists():
        raise SystemExit("Import already exists; create a new migration instead of rewriting applied checksums.")
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1]).resolve(strict=True)
    records, manifest, seen = [], [], set()
    for position, (slug, relative, name, target, ratio, description) in enumerate(SKILLS):
        path = source / relative
        raw = path.read_bytes()
        content = raw.decode("utf-8-sig").replace("\r\n", "\n").strip()
        if not content or "\x00" in content:
            raise ValueError(f"Invalid source: {path}")
        if sha256(raw) in seen:
            raise ValueError(f"Duplicate source: {path}")
        seen.add(sha256(raw))
        prompt = ADAPTER + f"### 文件：{path.name}\n\n" + content + "\n\n以上原文用于创作参考，执行时仍以开头的项目集成约定和本轮宿主工具/输出协议为准。"
        records.append({"import_key": f"desktop:{slug}", "name": name, "description": description,
                        "target_type": target, "system_prompt": prompt, "aspect_ratio": ratio,
                        "cover_url": "", "status": 1, "sort_order": 300 + position})
        manifest.append({"importKey": f"desktop:{slug}", "name": name, "targetType": target, "source": relative,
                         "sha256": sha256(raw), "promptCharacters": len(prompt)})
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    if "$desktopskills$" in payload:
        raise ValueError("Unexpected SQL delimiter in source")
    sql = """-- Generated by scripts/import-desktop-skills.py; immutable after Flyway applies it.
-- Preserve administrator edits and do not resurrect disabled/deleted imported definitions.
INSERT INTO skills (import_key, name, description, target_type, system_prompt, aspect_ratio, cover_url, status, sort_order)
SELECT incoming.import_key, incoming.name, incoming.description, incoming.target_type, incoming.system_prompt,
       incoming.aspect_ratio, incoming.cover_url, incoming.status, incoming.sort_order
FROM jsonb_to_recordset($desktopskills$
""" + payload + """
$desktopskills$::jsonb) AS incoming (
    import_key text, name text, description text, target_type text, system_prompt text,
    aspect_ratio text, cover_url text, status integer, sort_order integer
)
WHERE NOT EXISTS (SELECT 1 FROM skills existing WHERE existing.import_key = incoming.import_key
    OR (existing.name = incoming.name AND existing.target_type = incoming.target_type AND existing.deleted_at IS NULL))
ON CONFLICT DO NOTHING;
"""
    files = sorted(p for p in source.rglob("*") if p.is_file())
    copies = []
    for path in files:
        rel = path.relative_to(source)
        target = DESTINATION / "sources" / rel
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
        copies.append({"path": "sources/" + rel.as_posix(), "sha256": sha256(path.read_bytes()), "bytes": path.stat().st_size})
    (DESTINATION / "import-report.json").write_text(json.dumps(
        {"version": 1, "sourceLabel": "用户桌面 skill 文件夹", "skills": manifest, "sourceFiles": copies},
        ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    MIGRATION.write_text(sql, encoding="utf-8")
    print(json.dumps({"skills": len(records), "sourceFiles": len(copies), "migration": MIGRATION.name}, ensure_ascii=False))


if __name__ == "__main__":
    main()

"""Build a one-time Flyway seed from a local LibTV export; never execute its assets.

Usage: python scripts/import-libtv-skills.py <libtv-export-directory>
The output is immutable once generated. Existing skills are not updated.
"""
import collections
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'server/src/main/resources/db/migration/V39__Import_Local_Skills.sql'
ADAPTER = '''你是 Inspire Studio 创作技能助手。以下技能正文和参考文件用于指导创意与提示词编写。
运行约束：始终遵守主 Agent 的 CreationPlan 结构化协议；需要补充信息时使用 clarificationQuestion 和 choices，tasks 为空；只通过系统支持的任务类型生成图片或视频。
正文中提到的外部平台工具、脚本、文件系统或专用模型不代表本系统具备这些能力，不得声称已执行。缺少素材时请用户上传，无法支持的步骤应说明并提供可用替代流程。
参考文件已内嵌在下方，不需要访问原目录。尊重用户当前生成设置和确认步骤。

'''


def quote(value):
    return "'" + str(value).replace("'", "''") + "'"


def main():
    if OUTPUT.exists():
        raise SystemExit('Migration already exists; refusing to change its Flyway checksum.')
    source = Path(sys.argv[1]) / 'data/skills.json'
    skills = json.loads(source.read_text(encoding='utf-8-sig'))['skills']
    report = {'sourceSha256': hashlib.sha256(source.read_bytes()).hexdigest(),
              'imported': [], 'skipped': []}
    sql = ["-- Generated by scripts/import-libtv-skills.py. Do not edit after applying.",
           "ALTER TABLE skills ADD COLUMN import_key TEXT;",
           "CREATE UNIQUE INDEX idx_skills_import_key ON skills(import_key) WHERE import_key IS NOT NULL;",
           "SET LOCAL standard_conforming_strings = on;"]
    overrides = {item['importKey']: item['targetType'] for item in json.loads(
        (ROOT / 'third-party/skills/target-type-overrides.json').read_text(encoding='utf-8'))}
    seen = {}
    for skill in skills:
        key = skill['skillUuid']
        target_type = overrides.get('libtv:' + key, skill['resultTypeName'])
        body = (skill.get('markdownContent') or '').strip()
        files = sorted(skill.get('skillFiles') or [], key=lambda f: (not f.get('primary'), f['path']))
        chunks, contents = [], set()
        for filename, content in [('SKILL.md', body)] + [(f['path'], (f.get('content') or '').strip()) for f in files]:
            if content and content not in contents:
                contents.add(content)
                chunks.append('### 文件：' + filename + '\n\n' + content)
        reason = 'missing_definition' if not chunks else ('unsupported_type' if target_type not in ('image', 'video') else None)
        digest = hashlib.sha256(('\n\n'.join(sorted(contents))).encode()).hexdigest()
        identity = (target_type, digest)
        if not reason and identity in seen:
            reason = 'duplicate_definition:' + seen[identity]
        if reason:
            report['skipped'].append({'id': key, 'name': skill['name'], 'reason': reason})
            continue
        seen[identity] = key
        name = skill['name'].strip()
        assert 0 < len(name) <= 100 and '\x00' not in ''.join(chunks)
        prompt = ADAPTER + '\n\n'.join(chunks) + '\n\n以上内容作为创作参考；输出仍须遵循 CreationPlan 协议和当前系统支持的能力。'
        values = [name, skill.get('description') or '', target_type, prompt, '', 'libtv:' + key]
        sql.append('INSERT INTO skills(name,description,target_type,system_prompt,cover_url,import_key,status,sort_order) SELECT '
                   + ','.join(map(quote, values)) + ',1,1000 WHERE NOT EXISTS (SELECT 1 FROM skills WHERE import_key='
                   + quote('libtv:' + key) + ');')
        report['imported'].append({'id': key, 'name': name, 'type': target_type,
                                   'definitionSha256': digest, 'promptCharacters': len(prompt),
                                   'files': [f['path'] for f in files], 'pageUrl': skill.get('pageUrl')})
    OUTPUT.write_text('\n'.join(sql) + '\n', encoding='utf-8')
    destination = ROOT / 'third-party/skills'
    destination.mkdir(parents=True, exist_ok=True)
    (destination / 'libtv-import-report.json').write_text(json.dumps(report, ensure_ascii=False, indent=2), encoding='utf-8')
    print(json.dumps({'imported': len(report['imported']), 'types': dict(collections.Counter(x['type'] for x in report['imported'])),
                      'skipped': dict(collections.Counter(x['reason'].split(':')[0] for x in report['skipped'])),
                      'migrationBytes': OUTPUT.stat().st_size}, ensure_ascii=False))


if __name__ == '__main__':
    main()

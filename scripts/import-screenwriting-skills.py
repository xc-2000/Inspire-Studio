def sha256(content):
    return hashlib.sha256(content).hexdigest()


def compile_collection(source):
    records = []
    manifest = []
    seen = set()
    for position, (slug, directory, name, reference, description) in enumerate(SKILLS):
        files = [("SKILL.md", source / directory / "SKILL.md"), (reference, source / directory / reference)]
        definitions = []
        file_report = []
        for relative, path in files:
            raw = path.read_bytes()
            content = raw.decode("utf-8-sig").replace("\r\n", "\n").strip()
            if not content or "\x00" in content:
                raise ValueError(f"Invalid source: {path}")
            definitions.append(f"### 文件：{relative}\n\n{content}")
            file_report.append({"path": f"sources/{directory}/{relative}", "runtimePath": relative,
                                "sha256": sha256(raw), "characters": len(content)})
        identity = sha256("\n\n".join(definitions).encode())
        if identity in seen:
            raise ValueError(f"Duplicate skill definition: {name}")
        seen.add(identity)
        prompt = (ADAPTER + f"\n本技能必读配套指南：{reference}。\n\n" + "\n\n".join(definitions)
                  + "\n\n以上原文用于创作参考，执行时仍以开头的项目集成约定和本轮宿主工具/输出协议为准。")
        import_key = f"screenwriting:{slug}"
        records.append({"import_key": import_key, "name": name, "description": description,
                        "target_type": "video", "system_prompt": prompt, "aspect_ratio": "16:9",
                        "cover_url": "", "status": 1, "sort_order": 200 + position})
        manifest.append({"importKey": import_key, "name": name, "targetType": "video", "files": file_report,
                         "promptSha256": sha256(prompt.encode()), "promptCharacters": len(prompt)})
    return records, manifest


def build_sql(records):
    payload = json.dumps(records, ensure_ascii=False, indent=2)
    if "$screenwriting$" in payload:
        raise ValueError("Unexpected SQL delimiter in source")
    return """-- Generated by scripts/import-screenwriting-skills.py; immutable after Flyway applies it.
-- Preserve administrator edits and do not resurrect disabled/deleted imported definitions.
INSERT INTO skills (import_key, name, description, target_type, system_prompt, aspect_ratio, cover_url, status, sort_order)
SELECT incoming.import_key, incoming.name, incoming.description, incoming.target_type, incoming.system_prompt,
       incoming.aspect_ratio, incoming.cover_url, incoming.status, incoming.sort_order
FROM jsonb_to_recordset($screenwriting$
""" + payload + """
$screenwriting$::jsonb) AS incoming (
    import_key text, name text, description text, target_type text, system_prompt text,
    aspect_ratio text, cover_url text, status integer, sort_order integer
)
WHERE NOT EXISTS (SELECT 1 FROM skills existing WHERE existing.import_key = incoming.import_key
    OR (existing.name = incoming.name AND existing.target_type = incoming.target_type AND existing.deleted_at IS NULL))
ON CONFLICT DO NOTHING;
"""


def main():
    if MIGRATION.exists() or DESTINATION.exists():
        raise SystemExit("Import already exists; create a new migration instead of rewriting applied checksums.")
    if len(sys.argv) != 2:
        raise SystemExit(__doc__)
    source = Path(sys.argv[1]).resolve(strict=True)
    records, skills = compile_collection(source)
    source_files = sorted(path for path in source.rglob("*") if path.is_file())
    for path in source_files:
        if path.is_symlink() or not path.resolve().is_relative_to(source):
            raise ValueError(f"Source outside collection: {path}")
    sql = build_sql(records)
    copies = []
    for path in source_files:
        relative = path.relative_to(source)
        target = DESTINATION / "sources" / relative
        target.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(path, target)
        copies.append({"path": "sources/" + relative.as_posix(), "sha256": sha256(path.read_bytes()), "bytes": path.stat().st_size})
    report = {"version": 1, "sourceLabel": "用户提供的剧本 skill 合集", "skills": skills,
              "sourceFiles": copies, "attachmentCount": sum(path.suffix.lower() in (".doc", ".docx", ".xlsx") for path in source_files)}
    (DESTINATION / "import-report.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    MIGRATION.write_text(sql, encoding="utf-8")
    print(json.dumps({"skills": len(records), "sourceFiles": len(copies), "attachments": report["attachmentCount"],
                      "migration": MIGRATION.name}, ensure_ascii=False))


if __name__ == "__main__":
    main()
